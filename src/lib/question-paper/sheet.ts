// The answer sheet as a format-neutral model, shared by the PDF (HTML) and
// DOCX exporters so both contain exactly the same content in the same order.

import { QUESTION_TYPE_LABELS, detailLevelLabel, displayLabel, examTypeLabel, questionHeading } from "./constants";
import type { PublicJob, PublicQuestion } from "./types";

