export const DISCLAIMER =
  "These solutions were generated by AI and may contain mistakes. Check them against your textbook or teacher, especially any answer marked “Needs review”.";

export interface SheetQuestion {
  id: string;
  label: string;
  heading: string;          // "Question 5(b)"
  typeLabel: string;
  marks: number | null;
  contextMd: string | null;
  questionMd: string;
  options: Array<{ label: string; text: string; correct: boolean }>;
  match: { left: string[]; right: string[] } | null;
  diagramNote: string | null;
  status: PublicQuestion["answer_status"];
  correctOption: string | null;
  answerMd: string | null;
  explanationMd: string | null;
  finalAnswer: string | null;
  needsReview: boolean;
  reviewReason: string | null;
}

export interface SheetModel {
  title: string;
  fileName: string;
  meta: Array<{ label: string; value: string }>;
  generatedOn: string;
  sections: Array<{ title: string | null; questions: SheetQuestion[] }>;
  answerKey: Array<{ label: string; answer: string; flagged: boolean }>;
  flagged: Array<{ label: string; reason: string }>;
  stats: { total: number; answered: number; flagged: number };
}

function normOpt(s: string | null): string {
  return (s ?? "").replace(/[().\s]/g, "").toLowerCase();
}

export function buildSheet(job: PublicJob, questions: PublicQuestion[], now = new Date()): SheetModel {
  const sorted = [...questions].sort((a, b) => a.order_index - b.order_index);
  const sections: SheetModel["sections"] = [];
  for (const q of sorted) {
    const last = sections[sections.length - 1];
    const sq: SheetQuestion = {
      id: q.id,
      label: displayLabel(q.number_label),
      heading: questionHeading(q.number_label),
      typeLabel: QUESTION_TYPE_LABELS[q.type] ?? "Question",
      marks: q.marks,
      contextMd: q.context_md,
      questionMd: q.question_md || "_(The text of this question could not be read.)_",
      options: (q.options ?? []).map((o) => ({ ...o, correct: !!q.correct_option && normOpt(o.label) === normOpt(q.correct_option) })),
      match: q.match_pairs,
      diagramNote: q.has_diagram && q.diagram_description ? q.diagram_description : null,
      status: q.answer_status,
      correctOption: q.correct_option,
      answerMd: q.answer_md,
      explanationMd: q.explanation_md,
      finalAnswer: q.final_answer,
      needsReview: q.needs_review,
      reviewReason: q.review_reason,
    };
    if (last && last.title === q.section) last.questions.push(sq);
    else sections.push({ title: q.section, questions: [sq] });
  }

  const answerKey = sorted.map((q) => ({
    label: displayLabel(q.number_label),
    answer:
      q.answer_status === "answered"
        ? (q.answer_short || q.final_answer || (q.correct_option ? `Option ${q.correct_option}` : "See solution"))
        : q.answer_status === "cannot_answer" ? "Not answered (see review)" : q.answer_status === "failed" ? "Not generated" : "Pending",
    flagged: q.needs_review,
  }));

  const meta = [
    { label: "Class", value: job.class_level ? `Class ${job.class_level}` : "—" },
    { label: "Board", value: job.board ?? "—" },
    { label: "Subject", value: job.subject ?? "—" },
    { label: "Examination", value: examTypeLabel(job.exam_type) },
    { label: "Answer style", value: detailLevelLabel(job.detail_level) },
  ];

  return {
    title: "Question Paper Solutions",
    fileName: job.file_name,
    meta,
    generatedOn: now.toLocaleDateString("en-IN", { day: "numeric", month: "long", year: "numeric", timeZone: "Asia/Kolkata" }),
    sections,
    answerKey,
    flagged: sorted.filter((q) => q.needs_review).map((q) => ({ label: questionHeading(q.number_label), reason: q.review_reason ?? "Marked for review." })),
    stats: {
      total: sorted.length,
      answered: sorted.filter((q) => q.answer_status === "answered").length,
      flagged: sorted.filter((q) => q.needs_review).length,
    },
  };
}

/** Safe download name, e.g. "maths-paper-solutions.pdf". */
export function exportFileName(sourceName: string, ext: "pdf" | "docx"): string {
  const base = sourceName.replace(/\.[^.]+$/, "").replace(/[^\w\- ]+/g, "").trim().replace(/\s+/g, "-").slice(0, 60) || "question-paper";
  return `${base}-solutions.${ext}`;
}
